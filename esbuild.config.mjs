import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { readFile } from 'node:fs/promises';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const workerOptions = {
	entryPoints: ['src/task-search-worker.ts'],
	bundle: true,
	write: false,
	format: 'iife',
	platform: 'browser',
	target: 'es2018',
	minify: prod,
	metafile: true,
};

const context = await esbuild.context({
	plugins: [
		{
			name: 'embedded-task-search-worker',
			setup(build) {
				build.onLoad({ filter: /task-search-service\.ts$/ }, async (args) => {
					const worker = await esbuild.build(workerOptions);
					const source = await readFile(args.path, 'utf8');
					return {
						contents: source.replaceAll('__TAVERN_SEARCH_WORKER_SOURCE__', () =>
							JSON.stringify(worker.outputFiles[0].text),
						),
						loader: 'ts',
						watchFiles: [args.path, ...Object.keys(worker.metafile.inputs)],
					};
				});
			},
		},
	],
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2018',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: process.env.TAVERN_BUILD_OUTFILE ?? 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
